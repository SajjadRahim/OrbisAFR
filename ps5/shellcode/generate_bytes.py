#!/usr/bin/env python3
"""
Recompiles open_hook.c into position-independent shellcode and regenerates
open_hook_bytes.h.

Why this exists (read before touching open_hook.c):
  The compiled hook is injected directly into a running PS5 game's memory and
  jumped to from a patched PLT entry (see ../source/hook.cpp). There is no
  linker/loader step at injection time, so the extracted machine code must be
  100% self-contained: no calls into libc, no string literals (they'd live in
  .rodata, which we never copy over), no global/static data, no relocations
  of any kind. open_hook.c is written to satisfy that; this script is what
  verifies it and turns the result into a C byte array.

Usage:
    python3 generate_bytes.py

Requires: clang (targeting x86_64-freebsd-pc-elf), objcopy, readelf.
Exits non-zero and prints the offending relocation if open_hook.c no longer
compiles to pure .text — fix the C before re-running.
"""
import subprocess
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "open_hook.c")
OBJ = os.path.join(HERE, "open_hook.o")
BIN = os.path.join(HERE, "open_hook.bin")
OUT = os.path.join(HERE, "open_hook_bytes.h")


def run(cmd):
    print("+", " ".join(cmd))
    subprocess.run(cmd, check=True)


def main():
    run([
        "clang", "--target=x86_64-freebsd-pc-elf",
        "-fPIC", "-fPIE", "-ffreestanding", "-fno-builtin",
        "-fomit-frame-pointer", "-nostdlib",
        "-Wall", "-Wextra", "-O2",
        "-c", SRC, "-o", OBJ,
    ])

    reloc = subprocess.run(["readelf", "-r", OBJ], capture_output=True, text=True)
    if "There are no relocations" not in reloc.stdout:
        print("!! open_hook.o has relocations — it is NOT safe to use as raw shellcode:")
        print(reloc.stdout)
        sys.exit(1)

    run(["objcopy", "-O", "binary", "--only-section=.text", OBJ, BIN])

    with open(BIN, "rb") as f:
        data = f.read()

    with open(OUT, "w") as f:
        f.write("// Auto-generated by generate_bytes.py — do not edit by hand.\n")
        f.write(f"// {len(data)} bytes, compiled from open_hook.c. Verified: no relocations,\n")
        f.write("// no external symbols, pure .text (safe to inject as raw shellcode).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define AFR_OPEN_HOOK_SIZE {len(data)}\n")
        f.write("static const uint8_t afr_open_hook_code[AFR_OPEN_HOOK_SIZE] = {\n")
        for i in range(0, len(data), 16):
            row = data[i:i + 16]
            f.write("    " + ", ".join(f"0x{b:02x}" for b in row) + ",\n")
        f.write("};\n")

    print(f"OK: wrote {OUT} ({len(data)} bytes, 0 relocations)")


if __name__ == "__main__":
    main()
